/**
 * Role names come from the People dictionary, not this one. A role is called
 * the same thing in the picker, the rail and this table — duplicating the
 * strings here is how those drift apart.
 */
export function roleLabel(type: MemberTypeId, locale: Locale): string {
  return getPeopleString(locale, typeLabelKey(type));
}

